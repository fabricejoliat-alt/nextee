-- APNs registrations are private to the API and bound to a live login session.
create table public.native_push_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  session_id uuid not null references auth.sessions(id) on delete cascade,
  device_token text not null check (device_token ~ '^[0-9a-f]+$' and length(device_token) between 32 and 512 and length(device_token) % 2 = 0),
  environment text not null check (environment in ('sandbox', 'production')),
  bundle_id text not null check (bundle_id = 'golf.activitee.app'),
  locale text not null default 'fr' check (locale in ('fr','en','de','it')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (device_token, environment, bundle_id)
);
create index native_push_subscriptions_user_idx on public.native_push_subscriptions(user_id);
create index native_push_subscriptions_session_idx on public.native_push_subscriptions(session_id);
alter table public.native_push_subscriptions enable row level security;
revoke all on public.native_push_subscriptions from anon, authenticated;
grant all on public.native_push_subscriptions to service_role;
grant usage, select on sequence public.native_push_subscriptions_id_seq to service_role;

comment on table public.native_push_subscriptions is 'APNs devices; service-role API only. Logout/session deletion and account deletion cascade to registrations.';
