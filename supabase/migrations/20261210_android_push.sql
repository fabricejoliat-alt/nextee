-- Android FCM registrations are isolated from the existing APNs registrations.
create table public.android_push_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  session_id uuid not null references auth.sessions(id) on delete cascade,
  device_token text not null check (device_token ~ '^[A-Za-z0-9:_.-]+$' and length(device_token) between 32 and 4096),
  application_id text not null check (application_id = 'golf.activitee.app'),
  locale text not null default 'fr' check (locale in ('fr','en','de','it')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (device_token, application_id)
);
create index android_push_subscriptions_user_idx on public.android_push_subscriptions(user_id);
create index android_push_subscriptions_session_idx on public.android_push_subscriptions(session_id);
alter table public.android_push_subscriptions enable row level security;
revoke all on public.android_push_subscriptions from anon, authenticated;
grant all on public.android_push_subscriptions to service_role;
grant usage, select on sequence public.android_push_subscriptions_id_seq to service_role;
comment on table public.android_push_subscriptions is 'FCM devices; service-role API only. Session deletion and account deletion remove registrations.';
